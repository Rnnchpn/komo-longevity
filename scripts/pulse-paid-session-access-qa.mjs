import assert from 'node:assert/strict';
import {normalizeAppointmentId,verifyPaidSession,getAppointmentFromBrowser,scopedProgressStorage,keepBooking,clearBooking,BOOKING_STORAGE_KEY} from '../pulse-v14-src/online/session/paid-access.js';
import {saveProgress,loadProgress} from '../pulse-v14-src/online/session/session-progress.mjs';
import {readFileSync} from 'node:fs';
const app=readFileSync('pulse-v14-src/online/session/app.js','utf8');
const activation=readFileSync('pulse-v14-src/online/activate/app.js','utf8');
assert.equal(normalizeAppointmentId(' 12345 '),'12345');
for(const x of ['0','abc','12-23','3<script>','1234567891234',null])assert.equal(normalizeAppointmentId(x),null);
const saved=new Map();
const storage={getItem:k=>saved.get(k)??null,setItem:(k,v)=>saved.set(k,v),removeItem:k=>saved.delete(k)};
assert.equal(getAppointmentFromBrowser('?appointment=12345',storage),'12345');
assert.equal(keepBooking(storage,'12345'),true);
assert.equal(saved.get(BOOKING_STORAGE_KEY),'12345');
assert.equal(getAppointmentFromBrowser('',storage),'12345');
assert.equal(getAppointmentFromBrowser('?appointment=not-a-number',storage),'12345');
let called=0;
const accepted=async(url,opts)=>{
 called++;assert.equal(url,'/api/pulse-online-verify');
 assert.equal(opts.method,'POST');
 assert.ok(opts.headers.authorization.startsWith('Bearer '));
 assert.equal(opts.credentials,'omit');
 assert.equal(opts.cache,'no-store');
 assert.deepEqual(JSON.parse(opts.body),{appointmentId:'12345'});
 return {ok:true,status:200,json:async()=>({eligible:true,canStart:true,paid:true})};
};
assert.deepEqual(await verifyPaidSession({accessToken:'valid.jwt.token',appointmentId:'12345',fetcher:accepted}),{ok:true,appointmentId:'12345'});
assert.equal(called,1);
const blocked=async()=>({ok:true,status:200,json:async()=>({eligible:true,canStart:false,paid:true})});
assert.equal((await verifyPaidSession({accessToken:'valid.jwt.token',appointmentId:'12345',fetcher:blocked})).error,'paid_session_not_enabled');
const denied=async()=>({ok:false,status:403,json:async()=>({error:'booking_not_eligible'})});
assert.equal((await verifyPaidSession({accessToken:'valid.jwt.token',appointmentId:'12345',fetcher:denied})).error,'booking_not_eligible');
const noPayment=async()=>({ok:false,status:403,json:async()=>({error:'payment_not_confirmed'})});
assert.equal((await verifyPaidSession({accessToken:'valid.jwt.token',appointmentId:'12345',fetcher:noPayment})).error,'payment_not_confirmed');
assert.equal((await verifyPaidSession({accessToken:'',appointmentId:'12345',fetcher:accepted})).error,'authentication_required');
assert.equal((await verifyPaidSession({accessToken:'valid',appointmentId:'bad',fetcher:accepted})).error,'invalid_booking_id');
assert.equal(called,1,'denied requests never sent to server with empty auth/invalid ID');
const state={page:3,task:2,questionStep:4,answers:{safety:'no',walk10:'2'},
 checks:new Set(['chair','space','support','device']),results:{sts:{value:14,status:'done'}}};
const one=scopedProgressStorage(storage,'patient-a','12345');
const two=scopedProgressStorage(storage,'patient-b','12345');
const anotherBooking=scopedProgressStorage(storage,'patient-a','54321');
assert.equal(saveProgress(one,state,1_000),true);
assert.equal(loadProgress(two,1_001),null,'patient B cannot read patient A local progress');
assert.equal(loadProgress(anotherBooking,1_001),null,'unrelated booking cannot read progress');
assert.equal(loadProgress(one,1_001).results.sts.value,14);
assert.equal(loadProgress(storage,1_001),null,'original demo namespace isolated');
clearBooking(storage);
assert.equal(storage.getItem(BOOKING_STORAGE_KEY),null);
assert.ok(app.includes("verifyPaidSession({"),'every paid session enters through server check');
assert.ok(app.includes("getAppointmentFromBrowser(window.location.search,store)"));
assert.ok(app.includes("progressStore=scopedProgressStorage(store,user.id,bookingId)"));
assert.ok(app.includes('loadSecureDossier(session.data.session.access_token,bookingId)'), 'paid users must load their private dossier');
assert.ok(app.includes('const restored=paidContext?'), 'paid sessions restore remote data, not another account local state');
assert.ok(!app.includes("role.data?.role!=='admin'"),'non-admin paid branch must exist');
assert.ok(app.includes("const activationLink=PULSE_ROOT+'online/activate/'+prefilled"),'preserve a valid booking reference after login and on previews');
assert.ok(activation.includes("PULSE_ROOT=location.pathname.startsWith('/pulse-v14/')"),'preserve preview and custom-domain routes');
assert.ok(activation.includes("result.canStart===true"),'client does not link a paid session while disabled');
assert.ok(activation.includes("href=\"'+PULSE_ROOT+'online/session/?appointment="),'successful payment supplies booking reference');
console.log('[pulse-paid-session-access-qa] server-verified booking, disabled default gate, per-user isolation and access redirects passed');
