import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {INTAKE_GROUPS} from '../pulse-v14-src/online/session/intake-model.mjs';
import {buildMotionPassport,createDailyProgram,planTargets,programProgress,dayIndex,priorityNarrative,PROGRAM_VERSION} from '../pulse-v14-src/online/session/motion-passport.mjs';
import {passportMarkup,roadmapMarkup,dailyProgramMarkup} from '../pulse-v14-src/online/session/passport-view.js';
import {snapshotProgress,cleanProgram} from '../pulse-v14-src/online/session/session-progress.mjs';
import {buildPdfReportData,PDF_REPORT_VERSION} from '../pulse-v14-src/online/session/pdf-report.js';
const answers=Object.fromEntries(INTAKE_GROUPS.flatMap(g=>g.questions.map(q=>[
 q.id,Array.isArray(q.options[0])?q.options[0][0]:'0'
])));
answers.safety='no';
const result={sts:{status:'done',value:13,source:'webcam'},unipodal_left:{status:'review',value:7.8}};
const model=buildMotionPassport(answers,result,false);
assert.equal(model.index,100);
assert.equal(model.domains.length,4);
assert.equal(model.measuredCount,2);
assert.equal(model.flaggedCount,1);
assert.equal(model.planStatus,'eligible');
assert.equal(model.focus.length,2);
assert.ok(model.message.includes('pas une estimation'));
const half={...answers,pain:'4',fear:'3'};
assert.equal(buildMotionPassport(half,result,false).planStatus,'professional_review');
assert.ok(priorityNarrative(buildMotionPassport(half,result,false)).includes('avis')||
 priorityNarrative(buildMotionPassport(half,result,false)).includes('échange'));
assert.equal(buildMotionPassport({...answers,safety:'yes'},result,true).planStatus,'safety_hold');
const incomplete={...answers};delete incomplete.walk10;
assert.equal(buildMotionPassport(incomplete,result,false).index,null);
assert.equal(buildMotionPassport(incomplete,result,false).planStatus,'questionnaire_incomplete');
assert.equal(planTargets(1).walkMinutes,8);
assert.equal(planTargets(4).walkMinutes,15);
assert.equal(dayIndex('2026-10-01','2026-10-08'),8);
assert.equal(dayIndex('2026-10-01','2026-11-29'),28);
const program=createDailyProgram('2026-10-29');
program.entries['2026-10-29']={completed:['walk','recover'],effort:3,note:'marche confortable'};
assert.equal(programProgress(program).daysLogged,1);
assert.equal(programProgress(program).percent,4);
const sanitized=cleanProgram(program);
assert.equal(sanitized.entries['2026-10-29'].effort,3);
assert.equal(sanitized.entries['2026-10-29'].completed.length,2);
assert.equal(cleanProgram({...program,entries:{...program.entries,'2026-10-30':{completed:['fake'],effort:5,note:''}}}),null);
assert.equal(cleanProgram({...program,entries:{'2026-10-30':{completed:['walk'],effort:11,note:''}}}),null);
assert.equal(cleanProgram({...program,entries:{'2026-10-29':{completed:['walk'],effort:5,note:'A'.repeat(161)}}}),null);
const snap=snapshotProgress({page:4,task:5,questionStep:4,answers,checks:new Set(['chair','space']),results:result,program,
 rawFrames:'never'});
assert.equal(snap.program.entries['2026-10-29'].note,'marche confortable');
assert.equal(snap.rawFrames,undefined);
const doc=buildPdfReportData(answers,result,null,false,new Date('2026-10-29'),{program,mode:'PILOTE'});
assert.equal(doc.version,PDF_REPORT_VERSION);
assert.equal(doc.mode,'PILOTE');
assert.equal(doc.passport.index,100);
assert.equal(doc.passport.planStatus,'eligible');
assert.equal(doc.program.progress.daysLogged,1);
assert.equal(doc.motion.score,null,'no fabricated Motion Score');
const html=passportMarkup(answers,result,false);
assert.ok(html.includes('MOTION PASSPORT'));
assert.ok(html.includes('INDICE DE MOBILITÉ PERÇUE'));
assert.ok(html.includes('6</strong>')||html.includes('/ 6'));
assert.ok(roadmapMarkup(answers,result,false).includes('Pulse Daily'));
assert.ok(dailyProgramMarkup(answers,result,false,program).includes('id="daily-save"'));
assert.ok(dailyProgramMarkup(half,result,false,null).includes('Programme autonome non proposé'));
assert.ok(!dailyProgramMarkup(half,result,false,null).includes('start-pulse-daily'));
const app=readFileSync('pulse-v14-src/online/session/app.js','utf8');
const pdf=readFileSync('pulse-v14-src/online/session/pdf-report.js','utf8');
const edge=readFileSync('supabase/functions/motion-online-dossier/index.ts','utf8');
assert.ok(app.includes('state.program=program;persistProgress()'));
assert.ok(pdf.includes('MOTION PASSPORT  /  PREMIER BILAN'));
assert.ok(pdf.includes('Votre feuille de route'));
assert.ok(pdf.includes('Aucune equivalence avec un age locomoteur'));
assert.ok(edge.includes('sanitizeProgram(s.program)'));
assert.ok(edge.includes('EXERCISES'));
console.log('[pulse-passport-daily-qa] passport, no longevity claims, targeted domains, daily tracking and secure serialization passed');
