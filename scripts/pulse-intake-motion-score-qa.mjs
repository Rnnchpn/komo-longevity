import assert from 'node:assert/strict';
import {INTAKE_GROUPS,SCORING_GROUPS,QUESTION_COUNT,intakeProgress,scoreIntake,completeGroup,questionnaireFocus} from '../pulse-v14-src/online/session/intake-model.mjs';
import {calculateMotionScore,MOTION_ALGORITHM_VERSION} from '../pulse-v14-src/online/session/motion-score.mjs';
import {intakeMarkup} from '../pulse-v14-src/online/session/intake-view.js';
import {reportMarkup} from '../pulse-v14-src/online/session/intake-report.js';
const all=INTAKE_GROUPS.flatMap(group=>group.questions);
assert.equal(QUESTION_COUNT,22,'expected exactly 22 self-administered questions');
assert.equal(new Set(all.map(x=>x.id)).size,all.length,'all question IDs distinct');
assert.equal(all.length,26,'22 core and four optional context questions');
assert.equal(INTAKE_GROUPS[5].optional,true,'additional context does not modify the core index');
assert.equal(SCORING_GROUPS.reduce((s,g)=>s+g.weight,0),1,'domain weights total 100%');
assert.equal(INTAKE_GROUPS.length,6,'five core groups and one optional context section');
assert.equal(intakeProgress({}).completed,0);
assert.equal(scoreIntake({}).profileIndex,null,'no partial questionnaire score');
const best=Object.fromEntries(all.map(q=>[q.id,q.options[0] instanceof Array?q.options[0][0]:'0']));
const worse={...best};
for(const g of SCORING_GROUPS)for(const q of g.questions)worse[q.id]='4';
let bestScore=scoreIntake(best);
let worseScore=scoreIntake(worse);
assert.equal(bestScore.complete,true);
assert.equal(bestScore.profileIndex,100);
assert.equal(worseScore.profileIndex,0);
assert.equal(completeGroup(INTAKE_GROUPS[1],best),true);
assert.equal(questionnaireFocus(best).length,2);
const partial={...best};delete partial.walk10;
assert.equal(scoreIntake(partial).complete,false);
assert.equal(scoreIntake(partial).profileIndex,null,'missing mobility question prevents final index');
const noContext={...best};delete noContext.fall12;delete noContext.nearFall;delete noContext.painNow;delete noContext.activeTime;
assert.equal(scoreIntake(noContext).profileIndex,bestScore.profileIndex,'optional questions never alter core score');
assert.equal(completeGroup(INTAKE_GROUPS[5],noContext),true);
assert.ok(intakeMarkup(noContext,5).includes('Facultatif'));
assert.equal(scoreIntake(partial).domains.mobility,null,'no partial domain inference');
const wrong={...best,walk10:'10'};
assert.equal(scoreIntake(wrong).complete,false);
assert.ok(intakeMarkup(best,1).includes('Marcher dehors pendant 10 minutes'));
assert.ok(intakeMarkup(partial,1).includes('QUESTIONNAIRES'));
const report=reportMarkup(best,{},false);
assert.ok(report.includes('Motion Score indisponible'));
assert.ok(report.includes('INDICE DE PROFIL DÉCLARÉ'));
assert.ok(report.includes('TUG'));
assert.ok(report.includes('SPPB'));
assert.ok(report.includes('questionnaires')||report.includes('déclaratif'));
const invalid=calculateMotionScore();
assert.equal(invalid.complete,false);
assert.equal(invalid.score,null);
const base={sts30:14,tug3m:9,sppbBalance:3,stsP10:8,stsP90:20,tugP10:7,tugP90:13,
 normsSource:'Source de percentiles externe vérifiée par opérateur',operatorVerified:true,stsVerified:true};
const scored=calculateMotionScore(base);
assert.equal(scored.complete,true);
assert.equal(scored.score,62);
assert.equal(scored.version,MOTION_ALGORITHM_VERSION);
assert.equal(calculateMotionScore({...base,tug3m:null}).score,null,'TUG required');
assert.equal(calculateMotionScore({...base,sppbBalance:null}).score,null,'SPPB required');
assert.equal(calculateMotionScore({...base,stsP90:8}).score,null,'equal percentiles invalid');
assert.equal(calculateMotionScore({...base,stsP90:null}).score,null,'norm missing');
assert.equal(calculateMotionScore({...base,normsSource:''}).score,null,'source required');
assert.equal(calculateMotionScore({...base,operatorVerified:false}).score,null,'operator confirmation required');
assert.equal(calculateMotionScore({...base,stsVerified:false}).score,null,'STS confirmation required');
assert.equal(calculateMotionScore({...base,sppbBalance:5}).score,null,'SPPB limited 0 to 4');
assert.equal(calculateMotionScore({...base,sts30:100,tug3m:1,sppbBalance:4}).score,100,'weights clamped 0..100');
assert.equal(calculateMotionScore({...base,sts30:0,tug3m:50,sppbBalance:0}).score,0,'min clamped 0');
console.log('[pulse-intake-motion-score-qa] 22 questions, complete/missing scoring, domain weights and gated linear score passed');
