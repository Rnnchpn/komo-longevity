import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {INTAKE_GROUPS,scoreIntake} from '../pulse-v14-src/online/session/intake-model.mjs';
import {buildPdfReportData,PDF_REPORT_VERSION} from '../pulse-v14-src/online/session/pdf-report.js';
import {reportMarkup} from '../pulse-v14-src/online/session/intake-report.js';

const read=p=>readFileSync(p,'utf8');
const app=read('site/pulse-v14/online/session/app.js');
const report=read('site/pulse-v14/online/session/intake-report.js');
const pdf=read('site/pulse-v14/online/session/pdf-report.js');
const css=read('site/pulse-v14/online/session/styles.css');
const verify=read('api/pulse-online-verify.js');
const dossier=read('site/pulse-v14/online/session/secure-dossier.js');
for(const script of ['app.js','intake-report.js','pdf-report.js','secure-dossier.js']){
 const result=spawnSync(process.execPath,['--check','site/pulse-v14/online/session/'+script],{encoding:'utf8'});
 assert.equal(result.status,0,script+': '+result.stderr);
}
assert.ok(app.includes("id=\"check-device\"")&&app.includes("id=\"device-feedback\""),'Visible camera preflight');
assert.ok(app.includes("getUserMedia({audio:false,video:")&&app.includes("stream?.getTracks().forEach(track=>track.stop())"),'Preflight video track is explicitly stopped');
assert.ok(css.includes('.online-session-shell .device-preflight')&&css.includes('@media(max-width:640px)'), 'Preflight usable on mobile');
assert.ok(app.includes('beforeDownload(){')&&app.includes('dossierQueue?.flush()'));
assert.ok(app.includes('appointmentId:paidContext?.appointmentId||null'));
assert.ok(app.includes('verifyPaidSession({')&&app.includes('paidContext={userId:user.id,appointmentId:bookingId}'));
assert.ok(report.includes("mode:callbacks.isPaid?'ONLINE49':'DEMONSTRATION'"));
assert.ok(report.includes('secure_snapshot_not_saved')&&report.includes('callbacks.beforeDownload?.()'));
assert.ok(report.includes("if(!callbacks.isPaid){"),'Operator score engine is disabled in paid report binding');
assert.ok(report.includes('online-consultation-handoff')&&report.includes('confirmation Acuity'));
assert.ok(report.includes("persisted?'':'<button")&&report.includes("root.querySelector('#restart')?.addEventListener"));
assert.ok(css.includes('.online-report-paid .motion-operator-details{display:none!important}'));
assert.ok(pdf.includes("data.mode==='ONLINE49'?'BILAN ONLINE 49 EUR'"));
assert.ok(pdf.includes('Compte rendu initial produit apres votre bilan guide'));
assert.ok(pdf.includes('aucune validation professionnelle')||pdf.includes('aucune validation professionnelle'.replace('aucune','Aucune')));
assert.ok(pdf.includes("KOMO_Motion_'+(data.mode==='ONLINE49'"));
assert.ok(verify.includes("PULSE_ONLINE_PAID_SESSION_ENABLED==='true'"), 'Do not bypass server-side paid access');
assert.ok(verify.includes('payment_not_confirmed')&&verify.includes('ACUITY_API_KEY'));
assert.ok(dossier.includes('saveSecureDossier')&&dossier.includes('flush()'));
const answers=Object.fromEntries(INTAKE_GROUPS.flatMap(g=>g.questions.map(q=>[q.id,Array.isArray(q.options[0])?q.options[0][0]:'0'])));
answers.safety='no';
const tests={sts:{status:'done',value:14,source:'webcam'}};
const p=scoreIntake(answers);
assert.equal(p.complete,true);
const paid=buildPdfReportData(answers,tests,null,false,new Date('2026-10-29'),{mode:'ONLINE49',appointmentId:'123456789',program:null});
assert.equal(paid.version,PDF_REPORT_VERSION);
assert.equal(paid.mode,'ONLINE49');
assert.equal(paid.appointmentId,'123456789');
assert.equal(paid.reportStatus,'initial_unreviewed');
assert.equal(paid.passport.index,p.profileIndex);
assert.equal(paid.motion.score,null,'Do not invent missing TUG/SPPB');
const paidHtml=reportMarkup(answers,tests,false,true,null);
const demoHtml=reportMarkup(answers,tests,false,false,null);
assert.ok(!paidHtml.includes('id="compute-motion-score"'),'Paid client must never receive operator-only calculator inputs');
assert.ok(!paidHtml.includes('id="kms-tug"'),'Paid client cannot self-assert a TUG measurement');
assert.ok(demoHtml.includes('id="compute-motion-score"'),'Admin demo calculator preserved for controlled testing');
assert.ok(paidHtml.includes('online-consultation-handoff')&&paidHtml.includes('49 €'));

assert.equal(paid.observations.find(x=>x.id==='sts').value,14);
const tampered=buildPdfReportData(answers,tests,null,false,new Date('2026-10-29'),{mode:'ONLINE49',appointmentId:'<script>oops</script>'});
assert.equal(tampered.appointmentId,null,'Never render unvalidated appointment references');
const demo=buildPdfReportData(answers,{},null,false,new Date('2026-10-29'),{mode:'DEMONSTRATION',appointmentId:'123456789'});
assert.equal(demo.appointmentId,null);
assert.equal(demo.mode,'DEMONSTRATION');
console.log('[pulse-online49-report-qa] PASS · paid booking gating, secure flush, original patient measures, honest score and branded unreviewed PDF');
